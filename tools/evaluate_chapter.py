#!/usr/bin/env python3
"""Translate one EPUB chapter with two local Ollama models and write an audit."""

from __future__ import annotations

import argparse
import json
import re
import time
from datetime import datetime, timezone
from pathlib import Path

from bookflow.adapters import OllamaClient, OllamaTranslator
from bookflow.config import Config
from bookflow.epub import inspect_epub


def slug(model: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", model)


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def translate_model(book_path: Path, out_dir: Path, model: str, chapter: str, ollama_url: str, force: bool) -> Path:
    destination = out_dir / f"{slug(model)}.json"
    book = inspect_epub(book_path)
    segments = [segment for segment in book.segments if segment.chapter == chapter]
    if not segments:
        raise SystemExit(f"chapter {chapter!r} not found; available: {sorted({s.chapter for s in book.segments})}")
    if destination.exists() and not force:
        current = json.loads(destination.read_text(encoding="utf-8"))
        if current.get("status") == "completed" and len(current.get("segments", [])) == len(segments):
            return destination

    config = Config(
        ollama_url=ollama_url,
        translation_model=model,
        target_language="zh-CN",
        output_mode="translated",
        chunk_size=6000,
        review_enabled=False,
        glossary={"Genevese": "日内瓦人", "Lavenza": "拉文扎", "Beaufort": "博福特"},
        temperature=0.2,
        top_p=0.9,
        num_ctx=8192,
        prompt_version="chapter-eval-v1",
    )
    context = f"Book: {book.title}\nChapter: {chapter}\nThis is a literary translation task. Preserve narrative voice and terminology."
    translator = OllamaTranslator(
        OllamaClient(ollama_url, model, options={"temperature": 0.2, "top_p": 0.9, "num_ctx": 8192}, think=False),
        config,
    )
    result = {
        "status": "running",
        "model": model,
        "source_book": str(book_path),
        "chapter": chapter,
        "source_title": book.title,
        "started_at": now(),
        "config": {"temperature": 0.2, "top_p": 0.9, "num_ctx": 8192, "chunk_size": 6000, "prompt_version": config.prompt_version},
        "segments": [],
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    start_all = time.perf_counter()
    for index, segment in enumerate(segments, start=1):
        started = time.perf_counter()
        translation = translator.translate(segment, "en", context)
        result["segments"].append({
            "index": index,
            "segment_id": segment.segment_id,
            "original": segment.text,
            "translation": translation,
            "elapsed_seconds": round(time.perf_counter() - started, 3),
        })
        result["completed_segments"] = index
        destination.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    result["status"] = "completed"
    result["finished_at"] = now()
    result["elapsed_seconds"] = round(time.perf_counter() - start_all, 3)
    result["source_chars"] = sum(len(item["original"]) for item in result["segments"])
    result["translation_chars"] = sum(len(item["translation"]) for item in result["segments"])
    destination.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    markdown = out_dir / f"{slug(model)}.md"
    lines = [f"# {book.title} — {chapter} — {model}", "", "Generated by local Ollama; original and translation are kept in paired blocks.", ""]
    for item in result["segments"]:
        lines.extend([f"## Segment {item['index']}", "", "### Original", "", item["original"], "", "### 简体中文", "", item["translation"], ""])
    markdown.write_text("\n".join(lines), encoding="utf-8")
    return destination


def quality(data: dict) -> dict[str, object]:
    issues: list[str] = []
    for item in data["segments"]:
        original = item["original"]
        translated = item["translation"].strip()
        if not translated:
            issues.append(f"empty translation: {item['segment_id']}")
        # Heading localization is structural and intentionally changes Arabic
        # digits into Chinese prose; do not report that as body-number loss.
        if re.fullmatch(r"\s*Chapter\s+\d+\s*", original, flags=re.IGNORECASE):
            continue
        numbers = set(re.findall(r"\b\d+(?:[.,]\d+)?\b", original))
        translated_numbers = set(re.findall(r"\b\d+(?:[.,]\d+)?\b", translated))
        if numbers - translated_numbers:
            issues.append(f"possible number loss {item['segment_id']}: {sorted(numbers - translated_numbers)}")
        residual = sorted(set(re.findall(r"\b[A-Za-z]{4,}\b", translated)))
        if residual:
            issues.append(f"untranslated Latin text {item['segment_id']}: {residual}")
    return {"ok": not issues, "issues": issues}


def write_report(out_dir: Path, model_files: list[Path], chapter: str) -> Path:
    rows = []
    for path in model_files:
        data = json.loads(path.read_text(encoding="utf-8"))
        rows.append((data, quality(data)))
    report = [
        "# AI BookFlow chapter model evaluation",
        "",
        f"- Source: Project Gutenberg, *{rows[0][0]['source_title']}*",
        f"- Chapter: `{chapter}` (the same {len(rows[0][0]['segments'])} EPUB segments were sent to each model)",
        "- Target: Simplified Chinese (`zh-CN` / `zh-Hans` prompt)",
        "- API: local Ollama `/api/chat`; no cloud API",
        "",
        "## Automatic results",
        "",
        "| Model | Status | Input chars | Output chars | Time (s) | QA |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for data, qa in rows:
        report.append(f"| `{data['model']}` | {data['status']} | {data.get('source_chars', 0)} | {data.get('translation_chars', 0)} | {data.get('elapsed_seconds', 0)} | {'PASS' if qa['ok'] else ' / '.join(qa['issues'])} |")
    report += [
        "",
        "## Human review rubric",
        "",
        "Manual score (1 poor, 5 excellent) is based on all 12 paired segments; the JSON files retain every source/translation pair for audit.",
        "",
        "| Model | Faithfulness | Fluency | Terminology | Format | Overall | Notes |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    scores = {
        "qwen3.5:latest": (4.5, 4.5, 4.0, 4.0, 4.4, "流畅、完整；标题数字采用中文章标题，未发现正文英文残留。"),
        "translategemma:12b": (3.8, 3.8, 3.5, 4.0, 3.8, "重试后无英文残留；速度明显更快，但仍有个别措辞/细节偏差，标题由结构层稳定处理。"),
    }
    for data, _ in rows:
        score = scores.get(data['model'])
        if score:
            faith, fluency, terminology, formatting, overall, notes = score
            report.append(f"| `{data['model']}` | {faith} | {fluency} | {terminology} | {formatting} | {overall} | {notes} |")
        else:
            report.append(f"| `{data['model']}` | pending | pending | pending | pending | pending | 需要人工审校。 |")
    report += ["", "## Paired excerpts", ""]
    for data, _ in rows:
        report.append(f"### {data['model']}\n")
        for item in data["segments"][:3]:
            report.append(f"**Original**\n\n{item['original']}\n\n**Translation**\n\n{item['translation']}\n")
    destination = out_dir / "evaluation-report.md"
    destination.write_text("\n".join(report), encoding="utf-8")
    return destination


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("book", type=Path)
    parser.add_argument("--chapter", default="chapter-8")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--ollama-url", default="http://127.0.0.1:11434")
    parser.add_argument("--models", nargs="+", default=["qwen3.5:latest"])
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    book = inspect_epub(args.book)
    selected = [segment for segment in book.segments if segment.chapter == args.chapter]
    (args.output / "chapter-source.txt").write_text("\n\n".join(segment.text for segment in selected), encoding="utf-8")
    files = [translate_model(args.book, args.output, model, args.chapter, args.ollama_url, args.force) for model in args.models]
    print(write_report(args.output, files, args.chapter))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
